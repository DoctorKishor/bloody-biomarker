/**
 * Normalizes biomarker name to retrieve clinical description and reference range details.
 */
export const getBiomarkerClinicalDetails = (
    name: string,
    systemCategory?: string,
    existingRangeText?: string,
): BiomarkerClinicalDetail => {
    if (!name) {
        return {
            title: 'Parameter',
            subtitle: 'clinical metric',
            category: systemCategory ?? 'General',
            description: 'Laboratory biomarker evaluated to monitor physiological function and organ health.',
            clinicalRole: 'Part of clinical laboratory testing to detect metabolic deviations and guide healthcare management.',
            referenceRangeText: existingRangeText ?? 'Refer to laboratory report specification',
            highInterpretation: 'Elevated levels indicate physiological or metabolic stress requiring medical correlation.',
            lowInterpretation: 'Decreased levels indicate deficiency or decreased production requiring medical correlation.',
            sources: 'American Board of Internal Medicine (ABIM 2026), MedlinePlus',
        }
    }

    const clean = name.toLowerCase().replace(/[^a-z0-9]/g, '')

    // Check direct or alias match
    for (const key of Object.keys(BIOMARKER_CLINICAL_CATALOG)) {
        const item = BIOMARKER_CLINICAL_CATALOG[key]
        const cleanKey = key.toLowerCase().replace(/[^a-z0-9]/g, '')
        const cleanTitle = item.title.toLowerCase().replace(/[^a-z0-9]/g, '')

        if (clean === cleanKey || clean === cleanTitle || clean.includes(cleanKey) || cleanKey.includes(clean)) {
            return {
                ...item,
                referenceRangeText: existingRangeText && existingRangeText !== 'Default' ? existingRangeText : item.referenceRangeText,
            }
        }
    }

    // Dynamic medical summary for parameters not in explicit catalog
    const title = name
    const category = systemCategory ?? 'Biomarker Analysis'
    const refRange = existingRangeText && existingRangeText !== 'Default' ? existingRangeText : 'Laboratory Specific Reference Interval'

    return {
        title,
        subtitle: `${category.toLowerCase()} metric`,
        category,
        description: `${title} is a clinical laboratory parameter measured to assess ${category.toLowerCase()} function and systemic homeostasis. Keeping readings within the clinical reference interval supports cellular wellness, metabolic balance, and organ performance.`,
        clinicalRole: 'Evaluated during diagnostic and preventive health screenings to detect occult pathology, monitor organ function, and track clinical trends over time.',
        referenceRangeText: refRange,
        highInterpretation: 'Readings above the reference threshold indicate possible physiological stress, hyperfunction, or acute-phase response requiring medical correlation.',
        lowInterpretation: 'Readings below the reference threshold suggest possible insufficiency, impaired synthesis, or increased clearance requiring healthcare evaluation.',
        sources: 'American Board of Internal Medicine (ABIM 2026), Laboratory Medicine Reference Standards',
    }
}
